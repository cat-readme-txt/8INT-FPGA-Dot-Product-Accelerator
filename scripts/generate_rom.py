#!/usr/bin/env python3
"""Generate deterministic board self-test vectors and an independent oracle."""
from pathlib import Path
import random

ROOT = Path(__file__).resolve().parents[1]


def pack(values):
    return sum((value & 0xff) << (8 * lane) for lane, value in enumerate(values))


def main():
    rng = random.Random(20261018)
    vectors = [
        ([0] * 8, [0] * 8),
        ([-128] * 8, [-128] * 8),
        ([127] * 8, [127] * 8),
        ([-128] * 8, [127] * 8),
        ([127, -128] * 4, [-128, 127] * 4),
    ]
    while len(vectors) < 64:
        vectors.append(([rng.randrange(-128, 128) for _ in range(8)],
                        [rng.randrange(-128, 128) for _ in range(8)]))
    outputs = [sum(a * b for a, b in zip(av, bv)) for av, bv in vectors]
    lines = ["// Generated by scripts/generate_rom.py; lane 0 is the low byte."]
    for name, width, values in (
        ("rom_a", 64, [pack(av) for av, _ in vectors]),
        ("rom_b", 64, [pack(bv) for _, bv in vectors]),
        ("rom_expected", 19, [value & ((1 << 19) - 1) for value in outputs]),
    ):
        digits = (width + 3) // 4
        lines += [f"function [{width-1}:0] {name};", "    input [5:0] address;",
                  "    begin", "        case (address)"]
        for index, value in enumerate(values):
            lines.append(f"            6'd{index}: {name} = {width}'h{value:0{digits}x};")
        lines += [f"            default: {name} = {width}'d0;", "        endcase",
                  "    end", "endfunction", ""]
    (ROOT / "rtl/selftest_rom.svh").write_text("\n".join(lines))
    print("Generated 64 deterministic ROM vectors and exact expected results.")


if __name__ == "__main__":
    main()
